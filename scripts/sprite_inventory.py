"""Build a compact sprite name inventory without atlas coordinates or repeated border variants."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",default="docs/SPRITE_CATALOG.md",help="Project-relative generated inventory path")
    args=parser.parse_args()
    output=(ROOT/args.output).resolve()
    if not output.is_relative_to(ROOT): parser.error("Output must stay inside the project")
    base=json.loads((ROOT/"src/native/art/option2/sprites.json").read_text())
    rustic=json.loads((ROOT/"src/native/art/option3/sprites.json").read_text())
    groups={}
    remaining=[]
    patterns=[r"tile_border_(.+)_m\d+_(spring|summer|autumn|winter)_(sunny|partly_cloudy|rainy)_\d+",r"border_quarter_(.+)_(nw|ne|sw|se)_(fill|horizontal|vertical|outer|inner)_(spring|summer|autumn|winter)_(sunny|partly_cloudy|rainy)_\d+",r"tile_border_(.+)_fill_(spring|summer|autumn|winter)_(sunny|partly_cloudy|rainy)_\d+"]
    for name in sorted(rustic):
        for index,pattern in enumerate(patterns):
            match=re.fullmatch(pattern,name)
            if match:
                key=(index,match[1])
                groups[key]=groups.get(key,0)+1
                break
        else: remaining.append(name)
    lines=["# Compact sprite catalog","", "Generated by `python3 -B scripts/sprite_inventory.py`. See SPRITE_INVENTORY.md for missing-art requests and provenance. Names without an option marker exist in both packs.","", "## Dense border families","", "Seasons: spring, summer, autumn, winter. Weather: sunny, partly_cloudy, rainy. Variants: 0–3. Full terrain tiles use all 47 normalized eight-neighbor masks; quarter tiles use nw/ne/sw/se × fill/horizontal/vertical/outer/inner.",""]
    for (kind,material),count in sorted(groups.items()):
        template=[f"tile_border_{material}_m<MASK>_<SEASON>_<WEATHER>_<VARIANT>",f"border_quarter_{material}_<QUADRANT>_<SHAPE>_<SEASON>_<WEATHER>_<VARIANT>",f"tile_border_{material}_fill_<SEASON>_<WEATHER>_<VARIANT>"][kind]
        lines.append(f"- `{template}`: {count} sprites")
    lines.extend(["",f"## Other sprites ({len(remaining)} exact names)","", "```text"])
    lines.extend(name+(" [option 3 only]" if name not in base else "") for name in remaining)
    lines.extend(["```", ""])
    output.write_text("\n".join(lines))
    print(f"Cataloged {len(rustic)} sprites as {len(groups)} dense families and {len(remaining)} exact names")

if __name__=="__main__": main()
